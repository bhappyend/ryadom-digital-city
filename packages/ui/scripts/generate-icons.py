"""Generate static React JSX from the trusted original outline SVGs. No runtime XML."""
from pathlib import Path
import json
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[3]
SOURCE = ROOT / 'ryadom-digital-city/assets/icons'
TARGET = ROOT / 'packages/ui/src/icon-artwork.tsx'
ATTRS = {'stroke-width': 'strokeWidth', 'stroke-linecap': 'strokeLinecap',
         'stroke-linejoin': 'strokeLinejoin', 'stroke-opacity': 'strokeOpacity',
         'fill-rule': 'fillRule', 'clip-rule': 'clipRule'}


def jsx(node):
    tag = node.tag.split('}')[-1]
    attrs = ''.join(f' {ATTRS.get(k, k)}={json.dumps(v)}' for k, v in node.attrib.items())
    assert not node.text or not node.text.strip(), 'Unexpected text in icon'
    children = ''.join(jsx(child) for child in node)
    return f'<{tag}{attrs}>{children}</{tag}>' if children else f'<{tag}{attrs} />'


content = '// Generated by scripts/generate-icons.py from original SVGs. Do not hand edit.\n'
content += 'export const iconArtwork = {\n'
for path in sorted(SOURCE.glob('*.svg')):
    if path.name.startswith('tile-'):
        continue
    svg = ET.parse(path).getroot()
    assert svg.attrib['viewBox'] == '0 0 24 24'
    content += f'  {json.dumps(path.stem)}: <>{"".join(jsx(child) for child in svg)}</>,\n'
content += '} as const;\n'
if '--check' in sys.argv:
    assert TARGET.read_text(encoding='utf-8') == content, 'Icon JSX differs from originals'
    print('PASS: 29 outline SVGs match generated React JSX')
else:
    TARGET.write_text(content, encoding='utf-8')
    print('Generated icon-artwork.tsx')
